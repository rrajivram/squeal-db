macro_rules! define_keywords {
    ($($k:ident = $s:literal),* $(,)?) => {
        #[derive(Debug, Clone, Copy, PartialEq, Eq,Hash)]
        pub enum Keyword {
            $($k,)*
        }

        impl Keyword {
            pub fn get(value: &str) -> ::core::option::Option<Self> {
                match value {
                    $(_ if value.eq_ignore_ascii_case($s) => ::core::option::Option::Some(Self::$k),)*
                    _ => ::core::option::Option::None,
                }
            }

            pub fn is_reserved(value: &str) -> bool {
                Self::get(value).is_some()
            }
        }
    };
}

macro_rules! create_keywords {
    ($($k:ident = $s:literal),* $(,)?) => {
        $(
            #[derive(Debug, Clone, Copy, PartialEq, Eq,Hash)]
            pub struct $k {
                pub span: crate::span::TokenSpan
            }

            impl $k {
                pub fn new(span: crate::span::TokenSpan) -> Self {
                    Self {span}
                }
            }

        )*
    };
}

